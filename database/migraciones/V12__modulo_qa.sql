SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------
-- 1. Catalogo de casos: los metadatos que muestran la UI y los reportes.
--    El codigo (TC-SMK-001) es el mismo que lleva la anotacion @CasoQA
--    del metodo de prueba en el backend.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qa_casos (
    id_caso            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(20)  NOT NULL UNIQUE,
    tipo               VARCHAR(20)  NOT NULL,
    suite              VARCHAR(20)  NOT NULL,
    herramienta        VARCHAR(10)  NOT NULL,
    orden              SMALLINT     NOT NULL DEFAULT 1,
    nombre             VARCHAR(150) NOT NULL,
    objetivo           TEXT         NOT NULL,
    precondiciones     TEXT         NOT NULL,
    datos_prueba       TEXT         NOT NULL,
    resultado_esperado TEXT         NOT NULL,
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_en     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_qa_casos_codigo      CHECK (codigo ~ '^TC-[A-Z0-9]+-[0-9]{3}$'),
    CONSTRAINT chk_qa_casos_tipo        CHECK (tipo IN ('funcional', 'no_funcional')),
    CONSTRAINT chk_qa_casos_herramienta CHECK (herramienta IN ('api', 'ui', 'carga', 'modelo')),
    -- Cada suite pertenece a un solo tipo: la base no admite contradicciones
    CONSTRAINT chk_qa_casos_suite CHECK (
        (tipo = 'funcional'    AND suite IN ('smoke', 'sanity', 'regression', 'integration', 'e2e')) OR
        (tipo = 'no_funcional' AND suite IN ('performance', 'estres', 'soak', 'robustez_ia')))
);

COMMENT ON TABLE qa_casos IS
    'Catalogo de casos del Centro de Pruebas QA. Se tipifican solo por tipo de prueba (suite).';

CREATE OR REPLACE TRIGGER trg_qa_casos_actualizado
    BEFORE UPDATE ON qa_casos
    FOR EACH ROW EXECUTE FUNCTION fn_set_actualizado_en();


-- ---------------------------------------------------------------------
-- 2. Ejecuciones: una fila por cada vez que se pulsa "Ejecutar".
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qa_ejecuciones (
    id_ejecucion       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_publico       UUID         NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    id_usuario         BIGINT       REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    tipo               VARCHAR(20)  NOT NULL,
    suite              VARCHAR(20)  NOT NULL,
    alcance            VARCHAR(20)  NOT NULL,
    correo_destino     VARCHAR(150) NOT NULL,
    ambiente           VARCHAR(40)  NOT NULL DEFAULT 'local',
    parametros         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    estado             VARCHAR(20)  NOT NULL DEFAULT 'pendiente',
    resultado_global   VARCHAR(20),
    creado_en          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    inicio             TIMESTAMPTZ,
    fin                TIMESTAMPTZ,
    mensaje_error      TEXT,
    estado_correo      VARCHAR(20)  NOT NULL DEFAULT 'pendiente',
    error_correo       TEXT,
    correo_enviado_en  TIMESTAMPTZ,
    ruta_reporte_pdf   VARCHAR(500),
    ruta_reporte_html  VARCHAR(500),

    CONSTRAINT chk_qa_ejec_tipo      CHECK (tipo IN ('funcional', 'no_funcional')),
    CONSTRAINT chk_qa_ejec_suite     CHECK (
        (tipo = 'funcional'    AND suite IN ('smoke', 'sanity', 'regression', 'integration', 'e2e')) OR
        (tipo = 'no_funcional' AND suite IN ('performance', 'estres', 'soak', 'robustez_ia'))),
    CONSTRAINT chk_qa_ejec_alcance   CHECK (alcance IN ('suite_completa', 'seleccion')),
    CONSTRAINT chk_qa_ejec_correo    CHECK (
        correo_destino = LOWER(correo_destino) AND
        correo_destino ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT chk_qa_ejec_parametros CHECK (jsonb_typeof(parametros) = 'object'),
    CONSTRAINT chk_qa_ejec_estado    CHECK (estado IN ('pendiente', 'en_curso', 'finalizada', 'fallida')),
    CONSTRAINT chk_qa_ejec_resultado CHECK (
        resultado_global IS NULL OR resultado_global IN ('aprobada', 'con_fallos', 'incompleta')),
    CONSTRAINT chk_qa_ejec_correo_estado CHECK (
        estado_correo IN ('pendiente', 'enviado', 'error', 'no_configurado')),
    CONSTRAINT chk_qa_ejec_fechas    CHECK (inicio IS NULL OR fin IS NULL OR fin >= inicio),
    -- El estado y las fechas no pueden contradecirse:
    --   pendiente  -> sin inicio ni fin
    --   en_curso   -> con inicio, sin fin
    --   finalizada -> con inicio, fin y resultado global
    --   fallida    -> con fin y sin resultado global (pudo fallar antes de empezar)
    CONSTRAINT chk_qa_ejec_coherencia CHECK (
        (estado = 'pendiente'  AND inicio IS NULL     AND fin IS NULL     AND resultado_global IS NULL) OR
        (estado = 'en_curso'   AND inicio IS NOT NULL AND fin IS NULL     AND resultado_global IS NULL) OR
        (estado = 'finalizada' AND inicio IS NOT NULL AND fin IS NOT NULL AND resultado_global IS NOT NULL) OR
        (estado = 'fallida'    AND fin IS NOT NULL    AND resultado_global IS NULL))
);

COMMENT ON TABLE qa_ejecuciones IS
    'Ejecuciones del Centro de Pruebas QA: que se ejecuto, cuando, con que resultado y a quien se envio el reporte.';
COMMENT ON COLUMN qa_ejecuciones.resultado_global IS
    'aprobada: todos PASS. con_fallos: al menos un FAIL. incompleta: sin FAIL pero con SKIPPED o NOT_RUN.';

CREATE INDEX IF NOT EXISTS idx_qa_ejec_creado ON qa_ejecuciones(creado_en DESC);
-- Una sola ejecucion pendiente o en curso a la vez (una prueba de carga no
-- debe mezclarse con otra ejecucion)
CREATE UNIQUE INDEX IF NOT EXISTS uq_qa_ejec_activa ON qa_ejecuciones ((TRUE))
    WHERE estado IN ('pendiente', 'en_curso');


-- ---------------------------------------------------------------------
-- 3. Resultado de cada caso dentro de una ejecucion. Las filas se crean
--    al lanzar, en not_run; si la ejecucion se interrumpe, los casos que
--    no llegaron a correr quedan en not_run.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qa_resultados (
    id_resultado   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion   BIGINT      NOT NULL REFERENCES qa_ejecuciones(id_ejecucion) ON DELETE CASCADE,
    id_caso        BIGINT      NOT NULL REFERENCES qa_casos(id_caso) ON DELETE RESTRICT,
    orden          SMALLINT    NOT NULL,
    estado         VARCHAR(10) NOT NULL DEFAULT 'not_run',
    tipo_fallo     VARCHAR(20),
    mensaje_error  TEXT,
    paso_fallido   VARCHAR(255),
    observacion    TEXT,
    inicio         TIMESTAMPTZ,
    fin            TIMESTAMPTZ,

    CONSTRAINT uq_qa_resultados_caso   UNIQUE (id_ejecucion, id_caso),
    CONSTRAINT chk_qa_res_estado       CHECK (estado IN ('pass', 'fail', 'skipped', 'not_run')),
    -- El tipo de fallo existe solo cuando el caso fallo. El IS NOT NULL es
    -- necesario: NULL IN (...) da NULL y un CHECK con NULL no rechaza la fila
    CONSTRAINT chk_qa_res_tipo_fallo   CHECK (
        (estado = 'fail'  AND tipo_fallo IS NOT NULL AND tipo_fallo IN ('funcional', 'infraestructura')) OR
        (estado <> 'fail' AND tipo_fallo IS NULL)),
    CONSTRAINT chk_qa_res_fechas       CHECK (inicio IS NULL OR fin IS NULL OR fin >= inicio)
);

CREATE INDEX IF NOT EXISTS idx_qa_res_ejecucion ON qa_resultados(id_ejecucion, orden);


-- ---------------------------------------------------------------------
-- 4. Pasos ejecutados dentro de cada caso, con su evidencia.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qa_pasos (
    id_paso             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado        BIGINT       NOT NULL REFERENCES qa_resultados(id_resultado) ON DELETE CASCADE,
    numero              SMALLINT     NOT NULL,
    descripcion         VARCHAR(255) NOT NULL,
    resultado_observado TEXT,
    estado              VARCHAR(10)  NOT NULL,
    ruta_captura        VARCHAR(500),
    detalle_api         TEXT,
    registrado_en       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_qa_pasos_numero  UNIQUE (id_resultado, numero),
    CONSTRAINT chk_qa_pasos_numero CHECK (numero > 0),
    CONSTRAINT chk_qa_pasos_estado CHECK (estado IN ('ok', 'fallo'))
);

COMMENT ON COLUMN qa_pasos.ruta_captura IS
    'Ruta relativa a la carpeta de evidencias (qa-evidencias/{ejecucion}/...). NULL en pasos de API.';
COMMENT ON COLUMN qa_pasos.detalle_api IS
    'Peticion y respuesta resumidas. El encabezado Authorization se guarda enmascarado.';


-- ---------------------------------------------------------------------
-- 5. Metricas de las pruebas no funcionales (p95, throughput, recall...).
--    escalon solo se usa en la prueba de estres.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qa_metricas (
    id_metrica    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado  BIGINT        NOT NULL REFERENCES qa_resultados(id_resultado) ON DELETE CASCADE,
    orden         SMALLINT      NOT NULL DEFAULT 1,
    nombre        VARCHAR(60)   NOT NULL,
    valor         NUMERIC(14,4) NOT NULL,
    unidad        VARCHAR(20)   NOT NULL,
    umbral        NUMERIC(14,4),
    cumple        BOOLEAN,
    escalon       SMALLINT,

    CONSTRAINT uq_qa_metricas UNIQUE NULLS NOT DISTINCT (id_resultado, nombre, escalon),
    -- Si no hay umbral no se puede decir si cumple
    CONSTRAINT chk_qa_metricas_umbral CHECK (umbral IS NOT NULL OR cumple IS NULL)
);


-- ---------------------------------------------------------------------
-- 6. Lote etiquetado para la suite de robustez del modelo. Las URL que
--    proponga la IA (fase 7) entran como pendientes hasta que se revisen.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qa_lote_robustez (
    id_url           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url              VARCHAR(2048) NOT NULL UNIQUE,
    etiqueta         VARCHAR(10)   NOT NULL,
    categoria        VARCHAR(30)   NOT NULL,
    origen           VARCHAR(10)   NOT NULL DEFAULT 'dataset',
    estado_revision  VARCHAR(10)   NOT NULL DEFAULT 'aprobada',
    nota             VARCHAR(255),
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_qa_lote_etiqueta CHECK (etiqueta IN ('phishing', 'legitima')),
    CONSTRAINT chk_qa_lote_origen   CHECK (origen IN ('dataset', 'manual', 'ia')),
    CONSTRAINT chk_qa_lote_revision CHECK (estado_revision IN ('pendiente', 'aprobada', 'rechazada'))
);


