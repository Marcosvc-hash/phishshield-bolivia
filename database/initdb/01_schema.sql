CREATE TABLE analisis (
    id_analisis    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_publico   UUID         NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    id_usuario     BIGINT       REFERENCES usuarios(id_usuario)  ON DELETE SET NULL,
    id_empresa     BIGINT       REFERENCES empresas(id_empresa)  ON DELETE SET NULL,
    id_modelo      BIGINT       REFERENCES modelos_ia(id_modelo) ON DELETE SET NULL,
    tipo           VARCHAR(20)  NOT NULL,
    origen         VARCHAR(20)  NOT NULL DEFAULT 'web',
    contenido      TEXT         NOT NULL,
    contenido_hash CHAR(64)     NOT NULL,
    dominio        VARCHAR(255),
    resultado      VARCHAR(20)  NOT NULL,
    nivel_riesgo   NUMERIC(5,2) NOT NULL DEFAULT 0,
    tiempo_ms      INTEGER,
    ip_origen      INET,
    fecha_analisis TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_analisis_tipo      CHECK (tipo IN ('url', 'correo', 'imagen')),
    CONSTRAINT chk_analisis_origen    CHECK (origen IN ('extension', 'plugin_correo', 'web', 'api')),
    CONSTRAINT chk_analisis_resultado CHECK (resultado IN ('seguro', 'sospechoso', 'phishing')),
    CONSTRAINT chk_analisis_riesgo    CHECK (nivel_riesgo BETWEEN 0 AND 100),
    CONSTRAINT chk_analisis_tiempo    CHECK (tiempo_ms IS NULL OR tiempo_ms >= 0),
    -- El veredicto y el puntaje no pueden contradecirse
    CONSTRAINT chk_analisis_coherencia CHECK (
        (resultado = 'seguro'     AND nivel_riesgo <  40) OR
        (resultado = 'sospechoso' AND nivel_riesgo >= 40 AND nivel_riesgo < 70) OR
        (resultado = 'phishing'   AND nivel_riesgo >= 70))
);

COMMENT ON COLUMN analisis.contenido_hash IS 'SHA-256 del contenido: permite deduplicar y cachear análisis repetidos.';

CREATE INDEX idx_analisis_usuario_fecha ON analisis(id_usuario, fecha_analisis DESC);
CREATE INDEX idx_analisis_empresa_fecha ON analisis(id_empresa, fecha_analisis DESC);
CREATE INDEX idx_analisis_resultado     ON analisis(resultado);
CREATE INDEX idx_analisis_hash          ON analisis(contenido_hash);
CREATE INDEX idx_analisis_dominio       ON analisis(dominio) WHERE dominio IS NOT NULL;


-- Tabla puente: qué reglas se dispararon en cada análisis y cuánto sumaron
CREATE TABLE analisis_indicadores (
    id_analisis BIGINT       NOT NULL REFERENCES analisis(id_analisis)          ON DELETE CASCADE,
    id_regla    BIGINT       NOT NULL REFERENCES reglas_deteccion(id_regla)     ON DELETE CASCADE,
    valor       VARCHAR(255),
    aporte      NUMERIC(5,2) NOT NULL DEFAULT 0,

    PRIMARY KEY (id_analisis, id_regla),
    CONSTRAINT chk_indicadores_aporte CHECK (aporte BETWEEN -100 AND 100)
);


CREATE TABLE alertas (
    id_alerta          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_analisis        BIGINT      NOT NULL UNIQUE REFERENCES analisis(id_analisis) ON DELETE CASCADE,
    severidad          VARCHAR(10) NOT NULL DEFAULT 'media',
    estado             VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    canal              VARCHAR(20) NOT NULL DEFAULT 'app',
    id_asignado_a      BIGINT      REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    notas              TEXT,
    fecha_notificacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_cierre       TIMESTAMPTZ,

    CONSTRAINT chk_alertas_severidad CHECK (severidad IN ('baja', 'media', 'alta', 'critica')),
    CONSTRAINT chk_alertas_estado    CHECK (estado IN ('pendiente', 'en_revision', 'revisada', 'descartada')),
    CONSTRAINT chk_alertas_canal     CHECK (canal IN ('app', 'email', 'extension', 'webhook')),
    CONSTRAINT chk_alertas_cierre    CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_notificacion)
);

CREATE INDEX idx_alertas_abiertas ON alertas(severidad, fecha_notificacion DESC)
    WHERE estado IN ('pendiente', 'en_revision');


-- Retroalimentación del usuario: insumo para reentrenar el modelo
CREATE TABLE feedback_analisis (
    id_feedback BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_analisis BIGINT      NOT NULL REFERENCES analisis(id_analisis) ON DELETE CASCADE,
    id_usuario  BIGINT      REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    veredicto   VARCHAR(20) NOT NULL,
    comentario  TEXT,
    creado_en   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_feedback_veredicto CHECK (
        veredicto IN ('correcto', 'falso_positivo', 'falso_negativo')),
    CONSTRAINT uq_feedback_usuario UNIQUE (id_analisis, id_usuario)
);


