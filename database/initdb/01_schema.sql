CREATE TABLE lecciones (
    id_leccion   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo       VARCHAR(150) NOT NULL,
    descripcion  TEXT,
    nivel        VARCHAR(20)  NOT NULL DEFAULT 'basico',
    duracion_min SMALLINT,
    orden        SMALLINT     NOT NULL DEFAULT 1,
    publicada    BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_lecciones_nivel    CHECK (nivel IN ('basico', 'intermedio', 'avanzado')),
    CONSTRAINT chk_lecciones_duracion CHECK (duracion_min IS NULL OR duracion_min > 0)
);


CREATE TABLE progreso_lecciones (
    id_usuario    BIGINT      NOT NULL REFERENCES usuarios(id_usuario)  ON DELETE CASCADE,
    id_leccion    BIGINT      NOT NULL REFERENCES lecciones(id_leccion) ON DELETE CASCADE,
    estado        VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    puntaje       SMALLINT,
    completado_en TIMESTAMPTZ,

    PRIMARY KEY (id_usuario, id_leccion),
    CONSTRAINT chk_progreso_estado  CHECK (estado IN ('pendiente', 'en_curso', 'completada')),
    CONSTRAINT chk_progreso_puntaje CHECK (puntaje IS NULL OR puntaje BETWEEN 0 AND 100),
    CONSTRAINT chk_progreso_cierre  CHECK (
        (estado = 'completada' AND completado_en IS NOT NULL) OR
        (estado <> 'completada' AND completado_en IS NULL))
);


