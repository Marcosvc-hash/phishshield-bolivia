-- Resumen por empresa: lo que consume la pantalla principal del dashboard
CREATE OR REPLACE VIEW v_resumen_empresa AS
SELECT
    e.id_empresa,
    e.nombre                                                        AS empresa,
    COUNT(a.id_analisis)                                            AS total_analisis,
    COUNT(*) FILTER (WHERE a.resultado = 'phishing')                AS total_phishing,
    COUNT(*) FILTER (WHERE a.resultado = 'sospechoso')              AS total_sospechosos,
    ROUND(AVG(a.nivel_riesgo), 2)                                   AS riesgo_promedio,
    MAX(a.fecha_analisis)                                           AS ultimo_analisis
FROM empresas e
LEFT JOIN analisis a ON a.id_empresa = e.id_empresa
GROUP BY e.id_empresa, e.nombre;


-- Bandeja de alertas abiertas con su contexto
CREATE OR REPLACE VIEW v_alertas_abiertas AS
SELECT
    al.id_alerta,
    al.severidad,
    al.estado,
    an.tipo,
    an.contenido,
    an.nivel_riesgo,
    u.email        AS usuario_afectado,
    e.nombre       AS empresa,
    al.fecha_notificacion
FROM alertas al
JOIN analisis an ON an.id_analisis = al.id_analisis
LEFT JOIN usuarios u ON u.id_usuario = an.id_usuario
LEFT JOIN empresas e ON e.id_empresa = an.id_empresa
WHERE al.estado IN ('pendiente', 'en_revision');


-- Dominios más reportados como maliciosos
CREATE OR REPLACE VIEW v_top_dominios_maliciosos AS
SELECT
    dominio,
    COUNT(*)                      AS veces_detectado,
    ROUND(AVG(nivel_riesgo), 2)   AS riesgo_promedio,
    MAX(fecha_analisis)           AS ultima_deteccion
FROM analisis
WHERE resultado = 'phishing' AND dominio IS NOT NULL
GROUP BY dominio
ORDER BY veces_detectado DESC;
