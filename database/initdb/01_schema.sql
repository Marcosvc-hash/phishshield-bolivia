SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------
-- Función reutilizable: mantiene actualizado_en al día automáticamente
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_set_actualizado_en()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.actualizado_en := NOW();
    RETURN NEW;
END;
$$;


-- =====================================================================
-- A. ORGANIZACIÓN Y ACCESO
-- =====================================================================

CREATE TABLE empresas (
    id_empresa      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_publico    UUID          NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    nombre          VARCHAR(150)  NOT NULL,
    nit             VARCHAR(20)   UNIQUE,
    sector          VARCHAR(60),
    ciudad          VARCHAR(60),
    plan            VARCHAR(20)   NOT NULL DEFAULT 'basico',
    activa          BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    actualizado_en  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_empresas_plan CHECK (plan IN ('basico', 'profesional', 'empresarial')),
    CONSTRAINT chk_empresas_nit  CHECK (nit IS NULL OR nit ~ '^[0-9]{7,15}$')
);

COMMENT ON TABLE  empresas IS 'Pymes u organizaciones suscritas a PhishShield.';
COMMENT ON COLUMN empresas.uuid_publico IS 'Identificador expuesto en la API; el BIGINT nunca sale al exterior.';

CREATE TRIGGER trg_empresas_actualizado
    BEFORE UPDATE ON empresas
    FOR EACH ROW EXECUTE FUNCTION fn_set_actualizado_en();


CREATE TABLE usuarios (
    id_usuario        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_publico      UUID         NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    id_empresa        BIGINT       REFERENCES empresas(id_empresa) ON DELETE SET NULL,
    nombres           VARCHAR(80)  NOT NULL,
    apellidos         VARCHAR(80),
    email             VARCHAR(150) NOT NULL,
    password_hash     VARCHAR(255) NOT NULL,
    rol               VARCHAR(20)  NOT NULL DEFAULT 'usuario',
    estado            VARCHAR(20)  NOT NULL DEFAULT 'activo',
    email_verificado  BOOLEAN      NOT NULL DEFAULT FALSE,
    intentos_fallidos SMALLINT     NOT NULL DEFAULT 0,
    ultimo_login      TIMESTAMPTZ,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_en    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_usuarios_rol      CHECK (rol IN ('admin', 'analista', 'empresa', 'usuario')),
    CONSTRAINT chk_usuarios_estado   CHECK (estado IN ('activo', 'inactivo', 'bloqueado', 'pendiente')),
    CONSTRAINT chk_usuarios_intentos CHECK (intentos_fallidos BETWEEN 0 AND 100),
    -- El email se guarda siempre en minúsculas: evita duplicados tipo Juan@x.com / juan@x.com
    CONSTRAINT chk_usuarios_email    CHECK (email = LOWER(email) AND email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

CREATE UNIQUE INDEX uq_usuarios_email   ON usuarios(email);
CREATE        INDEX idx_usuarios_empresa ON usuarios(id_empresa) WHERE id_empresa IS NOT NULL;

CREATE TRIGGER trg_usuarios_actualizado
    BEFORE UPDATE ON usuarios
    FOR EACH ROW EXECUTE FUNCTION fn_set_actualizado_en();


-- Refresh tokens de JWT: permite cerrar sesión de un dispositivo puntual
CREATE TABLE sesiones (
    id_sesion          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario         BIGINT       NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    refresh_token_hash VARCHAR(255) NOT NULL UNIQUE,
    user_agent         VARCHAR(255),
    ip_origen          INET,
    expira_en          TIMESTAMPTZ  NOT NULL,
    revocada           BOOLEAN      NOT NULL DEFAULT FALSE,
    creado_en          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_sesiones_expira CHECK (expira_en > creado_en)
);

-- Índice parcial: solo interesan las sesiones vivas
CREATE INDEX idx_sesiones_activas ON sesiones(id_usuario) WHERE NOT revocada;


-- =====================================================================
-- B. INTELIGENCIA DE AMENAZAS (contexto boliviano)
-- =====================================================================

CREATE TABLE entidades_suplantadas (
    id_entidad      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL UNIQUE,
    tipo            VARCHAR(30)  NOT NULL,
    dominio_oficial VARCHAR(150),
    pais            CHAR(2)      NOT NULL DEFAULT 'BO',
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_entidades_tipo CHECK (
        tipo IN ('banco', 'billetera', 'gobierno', 'telco', 'ecommerce', 'educacion', 'otro'))
);

COMMENT ON TABLE entidades_suplantadas IS
    'Marcas bolivianas usadas como cebo en campañas de phishing. Es lo que diferencia a PhishShield de una herramienta genérica.';


CREATE TABLE dominios_lista (
    id_dominio  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dominio     VARCHAR(255) NOT NULL,
    lista       VARCHAR(10)  NOT NULL,
    id_entidad  BIGINT       REFERENCES entidades_suplantadas(id_entidad) ON DELETE SET NULL,
    fuente      VARCHAR(60)  NOT NULL DEFAULT 'manual',
    motivo      TEXT,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_dominios_lista  CHECK (lista IN ('blanca', 'negra', 'gris')),
    CONSTRAINT chk_dominios_minus  CHECK (dominio = LOWER(dominio)),
    CONSTRAINT uq_dominios_lista   UNIQUE (dominio, lista)
);

CREATE INDEX idx_dominios_activos ON dominios_lista(dominio) WHERE activo;


-- =====================================================================
-- C. MOTOR DE DETECCIÓN
-- =====================================================================

CREATE TABLE modelos_ia (
    id_modelo       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL,
    version         VARCHAR(20)  NOT NULL,
    tipo            VARCHAR(20)  NOT NULL,
    algoritmo       VARCHAR(60),
    exactitud       NUMERIC(5,2),
    precision_val   NUMERIC(5,2),
    recall_val      NUMERIC(5,2),
    f1_val          NUMERIC(5,2),
    umbral_phishing NUMERIC(5,2) NOT NULL DEFAULT 70,
    activo          BOOLEAN      NOT NULL DEFAULT FALSE,
    entrenado_en    DATE,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_modelos_tipo    CHECK (tipo IN ('url', 'texto', 'imagen', 'multimodal')),
    CONSTRAINT chk_modelos_umbral  CHECK (umbral_phishing BETWEEN 0 AND 100),
    CONSTRAINT chk_modelos_metricas CHECK (
        COALESCE(exactitud, 0)     BETWEEN 0 AND 100 AND
        COALESCE(precision_val, 0) BETWEEN 0 AND 100 AND
        COALESCE(recall_val, 0)    BETWEEN 0 AND 100 AND
        COALESCE(f1_val, 0)        BETWEEN 0 AND 100),
    CONSTRAINT uq_modelos_version  UNIQUE (nombre, version)
);

-- Regla de negocio en la BD: un solo modelo activo por tipo de análisis
CREATE UNIQUE INDEX uq_modelos_activo_por_tipo ON modelos_ia(tipo) WHERE activo;


CREATE TABLE reglas_deteccion (
    id_regla    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(40)  NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL,
    categoria   VARCHAR(20)  NOT NULL,
    peso        NUMERIC(5,2) NOT NULL DEFAULT 1,
    activa      BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_reglas_categoria CHECK (
        categoria IN ('url', 'contenido', 'remitente', 'adjunto', 'visual')),
    CONSTRAINT chk_reglas_peso CHECK (peso BETWEEN 0 AND 100)
);

COMMENT ON TABLE reglas_deteccion IS
    'Heurísticas explicables que acompañan al modelo de IA (permiten decirle al usuario POR QUÉ algo es phishing).';


-- =====================================================================
-- D. OPERACIÓN
