CREATE TABLE reportes (
    id_reporte       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa       BIGINT      NOT NULL REFERENCES empresas(id_empresa) ON DELETE CASCADE,
    periodo_inicio   DATE        NOT NULL,
    periodo_fin      DATE        NOT NULL,
    total_analisis   INTEGER     NOT NULL DEFAULT 0,
    total_phishing   INTEGER     NOT NULL DEFAULT 0,
    total_alertas    INTEGER     NOT NULL DEFAULT 0,
    generado_por     BIGINT      REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_reportes_periodo   CHECK (periodo_fin >= periodo_inicio),
    CONSTRAINT chk_reportes_totales   CHECK (
        total_analisis >= 0 AND total_alertas >= 0 AND
        total_phishing BETWEEN 0 AND total_analisis),
    CONSTRAINT uq_reportes_periodo    UNIQUE (id_empresa, periodo_inicio, periodo_fin)
);


CREATE TABLE auditoria (
    id_evento           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          BIGINT      REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    accion              VARCHAR(60) NOT NULL,
    entidad             VARCHAR(60),
    id_entidad_afectada BIGINT,
    detalle             JSONB,
    ip_origen           INET,
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_auditoria_fecha   ON auditoria(creado_en DESC);
CREATE INDEX idx_auditoria_detalle ON auditoria USING GIN (detalle);


